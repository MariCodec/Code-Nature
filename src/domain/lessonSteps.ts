/**
 * З яких кроків складається урок.
 *
 * Шлях учня (PLATFORM_UA, розділ 4) — це **порядок**, а не перелік того, що є
 * на сторінці: відео → теорія → практика. Сторінка мусить цей порядок показувати,
 * і правило одне:
 *
 * > Крок існує тоді й лише тоді, коли існує його вміст.
 *
 * Чиста функція без React і Redux — як `lessonCompletion`, `progression`
 * і `techCheck`. Форма сторінки ще зміниться (4c перебудує редактор усередині
 * кроку практики, 4d додасть панель виводу), але питання «які кроки має цей
 * урок» від цього не залежить.
 *
 * **Чому це домен, а не `&&` у розмітці.** Доки умови жили в JSX, сторінка
 * відповідала на них чотирма різними макетами, і кожна відповідь була своя:
 * урок-відео вмикався по `runtimeType`, інтро-екран — по наявності обʼєкта
 * відео, теорія — по довжині масиву, практика — по `hasEditor`. Зібрані в одному
 * місці, вони читаються як одне правило й перевіряються тестом, а не поглядом
 * на сім екранів.
 */

export type LessonStep =
  /** Плеєр, назва, опис, транскрипт. Живе **в одному місці** — див. 4b.5. */
  | { kind: "video" }
  /** Блоки теорії однією колонкою, шириною для читання. */
  | { kind: "theory" }
  /** Редактор (`files[]`) + preview + завдання. */
  | { kind: "practice" };

export type LessonStepKind = LessonStep["kind"];

export type LessonStepsInput = {
  /**
   * Важливе тут лише джерело: обʼєкт відео без адреси — це **не** відео,
   * а запис у контенті, якому автор ще не приклав файл.
   */
  videos: readonly { sourceUrl: string | null }[];
  theoryBlocks: readonly unknown[];
  tasks: readonly unknown[];
  /** З реєстру runtime-ів, а не з `runtimeType`: сторінка питає, не вгадує. */
  hasEditor: boolean;
};

const hasRealSource = (video: { sourceUrl: string | null }) =>
  typeof video.sourceUrl === "string" && video.sourceUrl.trim() !== "";

/**
 * Кроки уроку в порядку проходження. Порожній масив — теж відповідь: урок,
 * у якому нема ні відео, ні теорії, ні завдань, це недописаний контент,
 * і сторінка мусить сказати про це, а не намалювати порожнечу.
 */
export function getLessonSteps(input: LessonStepsInput): LessonStep[] {
  const steps: LessonStep[] = [];

  /*
   * Відео без `sourceUrl` кроку не дає, і це не дрібниця інтерфейсу.
   * Заглушка «відео буде додано» — це повідомлення **авторові**, показане
   * учневі; гірше, що поруч із нею стояла робоча кнопка «далі», і клік по ній
   * проставляв «відео додивлене» на уроці, чийого відео не існує.
   */
  if (input.videos.some(hasRealSource)) steps.push({ kind: "video" });

  if (input.theoryBlocks.length > 0) steps.push({ kind: "theory" });

  /*
   * Два складники, і жоден не зайвий. `hasEditor` без завдань — це урок, де
   * нема чого робити; завдання без редактора — завдання, яке нема де виконати.
   * Питання техчека сюди теж потраплять, але своїми кроками: розвилка «питання
   * чи редактор» іде від типу завдань, і це окрема робота (4b.6).
   */
  if (input.hasEditor && input.tasks.length > 0) steps.push({ kind: "practice" });

  return steps;
}
